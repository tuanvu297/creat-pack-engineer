// Fixed engineering command invoked ONLY by Codex command/exec. No inference.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import ts from 'typescript';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
const operation=process.argv[2];
const command=process.argv[3];
if(!['verify_temporal_source','verify_gateway_contract'].includes(command))throw new Error('NATIVE_COMMAND_SCOPE_DENIED');
if(!/^[a-f0-9-]{36}$/.test(operation??''))throw new Error('INVALID_OPERATION_ID');
const out=resolve('runtime-evidence/native',operation);
await mkdir(out,{recursive:true});
const emit=(x:object)=>process.stdout.write(JSON.stringify({operation_id:operation,pid:process.pid,timestamp:new Date().toISOString(),...x})+'\n');
emit({kind:'ACK',executor_worker_id:'CODEX_ENGINEERING_COMMAND',route:'codex-app-server/command/exec'});
emit({kind:'CHECKPOINT',phase:'TYPECHECK_AND_SOURCE_MANIFEST'});
const config=ts.readConfigFile('tsconfig.json',ts.sys.readFile);
if(config.error)throw new Error('TSC_CONFIG_ERROR');
const parsed=ts.parseJsonConfigFileContent(config.config,ts.sys,process.cwd());
const program=ts.createProgram(parsed.fileNames,{...parsed.options,noEmit:true});
const diagnostics=[...parsed.errors,...ts.getPreEmitDiagnostics(program)];
const status=diagnostics.length===0?0:1;
const text=ts.formatDiagnosticsWithColorAndContext(diagnostics,{getCanonicalFileName:p=>p,getCurrentDirectory:()=>process.cwd(),getNewLine:()=> '\n'});
const paths=['src/temporal/workflow.ts','src/temporal/bridge.ts','src/temporal/gateway.ts','src/temporal/result-events.ts','src/temporal/native-command.ts'];
const files=await Promise.all(paths.map(async path=>({path,sha256:createHash('sha256').update(await readFile(path)).digest('hex')})));
const gateway=await readFile('src/temporal/gateway.ts','utf8'),server=await readFile('src/temporal/server.ts','utf8');
const actions=['bootstrap','current_state','dispatch','task_status','get_run','active_missions','reconcile','submit_qa','callback_status'];
if(command==='verify_gateway_contract'&&!actions.every(a=>gateway.includes(a)&&server.includes(a)))throw new Error('GATEWAY_ACTION_MISSING');
const result={operation_id:operation,command,executor_worker_id:'CODEX_ENGINEERING_COMMAND',route:'codex-app-server/command/exec',evidence_class:'NATIVE_CODEX_COMMAND_NO_MODEL',exit_code:status,typecheck:status===0?'PASS':'FAIL',diagnostics:text.slice(0,8192),files,gateway_actions:actions,timestamp:new Date().toISOString()};
await writeFile(resolve(out,'result.json'),JSON.stringify(result,null,2)+'\n',{flag:'wx'});
emit({kind:'RESULT',typecheck:result.typecheck});
if(status!==0)process.exitCode=1;
